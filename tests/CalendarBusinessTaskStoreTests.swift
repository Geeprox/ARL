import Foundation
import Darwin

@main enum CalendarBusinessTaskStoreTests {
    static func main() throws {
        var count=0
        func expect(_ value:Bool,_ label:String) { precondition(value,label);count+=1 }
        func rejects(_ body:()throws->Void)->Bool { do {try body();return false}catch{return true} }
        let home=URL(fileURLWithPath:CommandLine.arguments[1])
        let fm=FileManager.default
        try fm.createDirectory(at:home,withIntermediateDirectories:false,attributes:[.posixPermissions:0o700])
        let store=CalendarBusinessTaskStore(home:home)
        let id=UUID().uuidString.lowercased()
        let draft=CalendarBusinessDraft(calendar_id:"fixture-calendar",title:"Synthetic journal",start:"2099-01-01T10:00:00+08:00",end:"2099-01-01T10:10:00+08:00",time_zone:"Asia/Shanghai",all_day:false,alarm_seconds:[300],recurrence:nil)
        let request=CalendarBusinessRequest(taskID:id,action:.create,draft:draft)
        let calendar=CalendarBusinessCalendar(id:"fixture-calendar",title:"Synthetic",source:"Fixture",writable:true,is_default:true)
        let claim=CalendarBusinessClaim(request:request,calendar:calendar)
        let root=home.appendingPathComponent("calendar-business-once-v1")
        expect(try store.lookup(id)==nil,"absent task")
        expect(!fm.fileExists(atPath:root.path),"status does not create store")
        try store.claim(claim)
        expect(try store.lookup(id)?.state == .attempting,"pending claim survives lookup")
        expect(try CalendarBusinessTaskStore(home:home).lookup(id)?.code == "outcome_unknown","restart does not replay")
        let claimFile=root.appendingPathComponent(id+".claim.json")
        var metadata=stat()
        expect(lstat(claimFile.path,&metadata)==0 && metadata.st_mode&0o777 == 0o600,"private mandatory record")
        expect(rejects{try store.claim(claim)},"same operation cannot claim twice")
        let changed=CalendarBusinessRequest(taskID:id,action:.create,draft:.init(calendar_id:"fixture-calendar",title:"Changed",start:draft.start,end:draft.end,time_zone:draft.time_zone,all_day:false,alarm_seconds:[],recurrence:nil))
        expect(rejects{try store.claim(.init(request:changed,calendar:calendar))},"changed body cannot reuse claim")
        let second=UUID().uuidString.lowercased()
        try store.claim(.init(request:.init(taskID:second,action:.create,draft:draft),calendar:calendar))
        expect(try store.lookup(second)?.state == .attempting,"independent task allowed beside unknown")
        let invalid=CalendarBusinessOperation(task_id:id,digest:String(repeating:"a",count:64),action:.create,state:.saved_local,code:"saved_local",event:nil)
        expect(rejects{try store.finish(invalid)},"terminal bound to original body")
        let terminal=CalendarBusinessOperation(task_id:id,digest:request.digest,action:.create,state:.saved_unreadable,code:"saved_unreadable",event:nil)
        try store.finish(terminal)
        expect(try store.lookup(id)==terminal,"terminal receipt survives reload")
        try store.finish(terminal)
        expect(try store.lookup(id)==terminal,"identical finish idempotent")
        let contradictory=CalendarBusinessOperation(task_id:id,digest:request.digest,action:.create,state:.outcome_unknown,code:"outcome_unknown",event:nil)
        expect(rejects{try store.finish(contradictory)},"terminal cannot be overwritten")
        let original=try Data(contentsOf:claimFile)
        try Data("{}".utf8).write(to:claimFile)
        expect(rejects{_ = try store.lookup(id)},"corrupt record fails closed")
        try original.write(to:claimFile)
        expect(try store.lookup(id)==terminal,"original receipt restored")
        let retained=home.appendingPathComponent("retained-store")
        try fm.moveItem(at:root,to:retained)
        try fm.createDirectory(at:root,withIntermediateDirectories:false,attributes:[.posixPermissions:0o700])
        expect(rejects{_ = try store.lookup(id)},"replacement directory cannot masquerade as missing task")
        expect(rejects{try store.claim(.init(request:.init(taskID:UUID().uuidString.lowercased(),action:.create,draft:draft),calendar:calendar))},"replacement directory cannot admit new effects")
        try fm.removeItem(at:root)
        try fm.moveItem(at:retained,to:root)
        expect(try store.lookup(id)==terminal,"original inode retains receipt")
        let terminalFile=root.appendingPathComponent(id+".terminal.json")
        let savedTerminal=root.appendingPathComponent("retained-terminal")
        try fm.moveItem(at:terminalFile,to:savedTerminal)
        try fm.createSymbolicLink(at:terminalFile,withDestinationURL:savedTerminal)
        expect(rejects{_ = try store.lookup(id)},"terminal symlink rejected")
        let target=CalendarBusinessTarget(calendar_id:calendar.id,event_id:"fixture-event",occurrence_start:draft.start,revision:String(repeating:"b",count:64))
        let originalEvent=CalendarBusinessEvent(target:target,draft:draft,editable:true,recurrence_supported:true,alarms_supported:true,repeating:false)
        let delete=CalendarBusinessClaim(request:.init(taskID:UUID().uuidString.lowercased(),action:.delete,target:target),calendar:calendar)
        let details=try CalendarBusinessConfirmation.details(delete,current:originalEvent)
        expect(details.contains(draft.title) && details.contains(draft.start) && details.contains(draft.end) && details.contains("全天：否"),"delete confirmation binds original title and full interval")
        expect(rejects{_ = try CalendarBusinessConfirmation.details(delete,current:nil)},"missing original cannot be confirmed")
        let update=CalendarBusinessClaim(request:.init(taskID:UUID().uuidString.lowercased(),action:.update,target:target,draft:changed.draft),calendar:calendar)
        let editedDetails=try CalendarBusinessConfirmation.details(update,current:originalEvent)
        expect(editedDetails.contains("Synthetic journal") && editedDetails.contains("Changed"),"edit confirmation shows original and replacement")
        print("PASS "+String(count)+" Calendar durable-claim checks; EventKit=0 permissions=0 business_writes=0")
    }
}
