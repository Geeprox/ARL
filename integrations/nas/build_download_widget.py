"""Generate the static native resource from its single JS/HTML source pair."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parent
TARGET = ROOT / "native/NASDownloadWidget.swift"
URI = "ui://arl/nas-download-v1.html"


def html():
    template = (ROOT / "download_widget.html").read_text()
    core = (ROOT / "download_widget.js").read_text()
    if template.count("/* ARL_NAS_DOWNLOAD_CORE */") != 1 or "</script" in core.lower():
        raise ValueError("invalid_widget_source")
    return template.replace("/* ARL_NAS_DOWNLOAD_CORE */", core)


def source():
    return '''// Generated by integrations/nas/build_download_widget.py; edit the JS/HTML sources.
import Foundation

enum NASDownloadWidget {
    static let uri = "''' + URI + '''"
    static let mimeType = "text/html;profile=mcp-app"
    static var listing: [String:Any] {
        ["uri":uri,"name":"ARL NAS download","mimeType":mimeType,
         "description":"Download one selected NAS file after byte and SHA verification."]
    }
    static var resource: [String:Any] {
        ["uri":uri,"mimeType":mimeType,"text":html,
         "_meta":["ui":["prefersBorder":true,"csp":["connectDomains":[],"resourceDomains":[]]],
                  "openai/widgetDescription":"Prepare and download the selected NAS file using the host's file APIs."]]
    }
    static let html = ####"""
''' + html() + '''
"""####
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    wanted = source()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text() != wanted:
            raise SystemExit("NAS widget native resource is stale")
    else:
        TARGET.write_text(wanted)


if __name__ == "__main__": main()
